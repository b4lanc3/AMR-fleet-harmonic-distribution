// FactoryLines: gz-sim system running the work cells at both ends of every
// production / packaging line from the MES state (fleet manager, simulated
// MES) - every carton and every product the MES counts is visible:
//
//   input cell : the station arm takes the carton off the AMR deck and puts
//                it on a free slot of the pedestal beside the line; the open
//                carton shows its products; the loader arm takes them one by
//                one (one per takt) and puts them on the belt; an empty
//                carton goes to the stack of folded cartons
//   belt       : every product rides from end to end and changes its look in
//                the middle (machined part -> product, product -> wrapped)
//   output cell: the loader arm packs every product into the open carton on
//                the pedestal; a full carton is closed and waits on its slot;
//                the station arm puts the oldest full carton on the AMR and
//                fetches a new carton from the stack for the next products
//
// The MES publishes, per line, on <topic> (std_msgs/String through the bridge):
//   "B1=run,in,open,fill,out|age age ...;C1=..."
//     run   0 while the line is blocked (nothing moves)
//     in    full cartons waiting on the input pedestal
//     open  products left in the open input carton
//     fill  products in the output carton being filled
//     out   full output cartons waiting for an AMR
//     age   seconds since every product on the way was started (oldest first):
//           [0, load) loader arm, [load, load + belt) belt, then the loader
//           arm of the output cell; at load + belt + drop it is in the carton
//   "G1=n;..." cartons loaded into the truck at every shipping gate
// so the arms of the loaders are a pure function of the ages.  The station
// arms are driven by the AMRs as before: when the arm holds the load on the
// deck (input) or has put the carton on the deck (output) it publishes
// "<station>:<amr>" on /factory/station_handover and the fleet manager ends
// the AMR's unloading / loading.
//
// Shipping gates: the station arm takes the carton off the AMR onto the dock
// conveyor; it runs through the open door, the telescopic boom reaches to
// the stack face in the trailer and the carton is put onto the stack (rows
// of 4 x 3 from the front wall to the doors).  A full truck is replaced by an
// empty one.  The stack follows the MES count once the conveyor is empty.
//
// All moving parts are static visual-only models of the world (generated by
// generate_world: fl_<station>_arm_*, fl_<station>_ld_*, fl_<station>_box<k>,
// _tray<k>, _hbox, _htray, fl_<line>_a<k> / _b<k>) posed by this system:
// no physics cost.

